#!/usr/bin/env python3
"""Writes crates/tandaiturun/credits.tsv: every crate compiled into the app on
at least one platform
(name, version, licence, repository), shown under Help → About → Libraries.

    python3 scripts/gen-credits.py

Run it after changing dependencies; CI fails when the file is out of date.
Dev- and build-only dependencies are left out: they are not part of the app.
"""
import json
import os
import subprocess
import sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
meta = json.loads(subprocess.check_output(
    ["cargo", "metadata", "--format-version", "1", "--locked"], cwd=root))
packages = {p["id"]: p for p in meta["packages"]}
nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
app = next(p["id"] for p in meta["packages"] if p["name"] == "tandaiturun")
own = {p["id"] for p in meta["packages"] if p["source"] is None}

seen, stack = set(), [app]
while stack:
    pid = stack.pop()
    if pid in seen:
        continue
    seen.add(pid)
    for dep in nodes[pid]["deps"]:
        kinds = {k["kind"] for k in dep["dep_kinds"]}
        if kinds & {None, "normal"} or None in kinds:
            stack.append(dep["pkg"])

rows = []
for pid in seen - own:
    p = packages[pid]
    licence = " ".join((p.get("license") or "see repository").replace("/", " OR ").split())
    repo = p.get("repository") or p.get("homepage") or f"https://crates.io/crates/{p['name']}"
    rows.append((p["name"].lower(), p["name"], p["version"], licence, repo))
rows.sort()

out = os.path.join(root, "crates", "tandaiturun", "credits.tsv")
with open(out, "w", encoding="utf-8") as f:
    f.write("# Generated by scripts/gen-credits.py: name, version, licence, repository.\n")
    for _, name, version, licence, repo in rows:
        f.write(f"{name}\t{version}\t{licence}\t{repo}\n")
print(f"{len(rows)} crates → {os.path.relpath(out, root)}", file=sys.stderr)
